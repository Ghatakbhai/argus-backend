--
-- Phase 6 computed FIRE/SUPPRESSED/ABSTAIN in memory and wrote a JSON file.
-- That was fine for one team run by hand; it cannot answer Phase 7's own
-- questions ("alert satisfaction across 15 teams", "did the multi-source
-- pipeline beat Part I's 65.5% ceiling"), because nothing durable records
