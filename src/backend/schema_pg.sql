-- 1. Provenance ------------------------------------------------------------

CREATE TABLE source (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       UUID NOT NULL REFERENCES tenant(id) ON DELETE CASCADE,
    name            TEXT NOT NULL,
    base_url        TEXT NOT NULL,
    UNIQUE (id, tenant_id),
    UNIQUE (tenant_id, name)
);

CREATE TABLE snapshot (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       UUID NOT NULL REFERENCES tenant(id) ON DELETE CASCADE,
    source_id       BIGINT NOT NULL,
    project_id      BIGINT NOT NULL,
    observed_at     TEXT NOT NULL,
    started_at      TEXT NOT NULL,
    completed_at    TEXT,
    is_complete     INTEGER NOT NULL DEFAULT 0 CHECK (is_complete IN (0,1)),
    tool_version    TEXT,
    notes           TEXT,
    UNIQUE (id, tenant_id),
    FOREIGN KEY (source_id, tenant_id) REFERENCES source(id, tenant_id)
);

CREATE TABLE "fetch" (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       UUID NOT NULL REFERENCES tenant(id) ON DELETE CASCADE,
    snapshot_id     BIGINT NOT NULL,
    url             TEXT NOT NULL,
    purpose         TEXT NOT NULL,
    attempt         INTEGER NOT NULL,
    tool            TEXT NOT NULL,
    requested_at    TEXT NOT NULL,
    duration_ms     INTEGER,
    outcome         TEXT NOT NULL CHECK (outcome IN ('ok','failed','corrupt','empty')),
    http_status     INTEGER,
    error_detail    TEXT,
    UNIQUE (id, tenant_id),
    FOREIGN KEY (snapshot_id, tenant_id) REFERENCES snapshot(id, tenant_id)
);
CREATE INDEX ix_fetch_snapshot ON "fetch"(tenant_id, snapshot_id);
CREATE INDEX ix_fetch_url      ON "fetch"(tenant_id, snapshot_id, url);
CREATE INDEX ix_fetch_outcome  ON "fetch"(tenant_id, snapshot_id, outcome);

