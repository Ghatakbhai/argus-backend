CREATE INDEX ix_webhookdelivery_installation ON webhook_delivery(tenant_id, installation_id);

-- ===========================================================================
-- 10. The clocks — views, ported.
--
-- security_invoker = true is load-bearing, not tidiness (D-129). A Postgres
-- view without it checks the underlying tables' RLS against the VIEW OWNER,
-- not the caller — which would have made these three views a hole straight
-- through the isolation model. The isolation test suite has a case for
-- exactly this.
--
-- julianday() does not exist in Postgres. TRUNC (not FLOOR) reproduces
-- SQLite's CAST-toward-zero behaviour, so Phase 3's numbers still reproduce.
-- ===========================================================================

CREATE VIEW v_item_clock WITH (security_invoker = true) AS
SELECT
    w.id                                        AS work_item_id,
    w.tenant_id                                 AS tenant_id,
    s.observed_at                               AS observed_at,
    MAX(e.occurred_at)                          AS last_human_at,
    TRUNC(EXTRACT(EPOCH FROM (s.observed_at::timestamptz
                              - MAX(e.occurred_at)::timestamptz)) / 86400)::int
                                                AS days_silent,
    MAX(CASE WHEN e.date_precision <> 'exact' THEN 1 ELSE 0 END)
                                                AS is_lower_bound,
    COUNT(e.id)                                 AS human_event_count
FROM work_item w
JOIN snapshot s ON s.id = w.snapshot_id AND s.tenant_id = w.tenant_id
LEFT JOIN event e
       ON e.work_item_id = w.id
      AND e.tenant_id = w.tenant_id
      AND e.counts_as_human = 1
      AND e.occurred_at IS NOT NULL
GROUP BY w.id, w.tenant_id, s.observed_at;

CREATE VIEW v_actor_item_clock WITH (security_invoker = true) AS
SELECT
    e.work_item_id                              AS work_item_id,
    e.tenant_id                                 AS tenant_id,
    e.actor_id                                  AS actor_id,
    s.observed_at                               AS observed_at,
    MAX(e.occurred_at)                          AS last_action_at,
    TRUNC(EXTRACT(EPOCH FROM (s.observed_at::timestamptz
                              - MAX(e.occurred_at)::timestamptz)) / 86400)::int
                                                AS days_silent,
    MAX(CASE WHEN e.date_precision <> 'exact' THEN 1 ELSE 0 END)
                                                AS is_lower_bound
FROM event e
JOIN work_item w ON w.id = e.work_item_id AND w.tenant_id = e.tenant_id
JOIN snapshot s  ON s.id = w.snapshot_id  AND s.tenant_id = w.tenant_id
WHERE e.counts_as_human = 1
  AND e.occurred_at IS NOT NULL
  AND e.actor_id IS NOT NULL
GROUP BY e.work_item_id, e.tenant_id, e.actor_id, s.observed_at;

CREATE VIEW v_item_confidence WITH (security_invoker = true) AS
SELECT
    w.id                                        AS work_item_id,
    w.tenant_id                                 AS tenant_id,
    COUNT(g.id)                                 AS gap_count,
    string_agg(DISTINCT g.gap_type, ',')        AS gap_types,
    CASE WHEN COUNT(g.id) = 0 THEN 'high' ELSE 'low' END AS confidence
FROM work_item w
LEFT JOIN evidence_gap g
       ON g.work_item_id = w.id AND g.tenant_id = w.tenant_id
GROUP BY w.id, w.tenant_id;

-- ===========================================================================
-- Row-Level Security. Applied by loop rather than by 32 copy-pasted blocks so
-- that a table added later cannot silently be left unprotected — the
-- verification query at the bottom fails loudly if one is.
-- ===========================================================================

DO $rls$
DECLARE t text;
BEGIN
    FOR t IN
        SELECT tablename FROM pg_tables
        WHERE schemaname = 'public'
          -- pending_installation joins this exclusion list at 7.2: it has no
          -- tenant_id column at all (there is no tenant yet for an
          -- installation nobody has claimed), so the generic policy below
          -- would fail to even compile against it.
          AND tablename NOT IN ('tenant','tenant_api_key','audit_log','pending_installation')
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format(
            'CREATE POLICY tenant_isolation ON %I
                 USING (tenant_id = argus_current_tenant())
                 WITH CHECK (tenant_id = argus_current_tenant())', t);
    END LOOP;
END
$rls$;

-- Fail the migration outright if any data table escaped the loop above.
-- `tenant` gets its own policy: its primary key IS the tenant id. Without
-- this, any authenticated request could list every pilot team by name --
-- which is exactly what the first draft of /v1/me did.
ALTER TABLE tenant ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenant FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_self ON tenant
    USING (id = argus_current_tenant())
    WITH CHECK (id = argus_current_tenant());

DO $verify$
DECLARE missing text;
BEGIN
    SELECT string_agg(c.relname, ', ') INTO missing
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
      AND c.relname NOT IN ('tenant_api_key','audit_log','pending_installation')
      AND NOT (c.relrowsecurity AND c.relforcerowsecurity);
    IF missing IS NOT NULL THEN
        RAISE EXCEPTION 'RLS not forced on: %', missing;
    END IF;
END
$verify$;
