CREATE INDEX ix_ingestrun_tenant ON ingest_run(tenant_id, started_at DESC);

-- One row per sprint_filter decision. SUPPRESSED and ABSTAIN rows are stored
-- as deliberately as FIRE rows: the suppression count IS the measurement
-- Phase 6's kill criterion was about, and throwing it away would leave the
-- pilot unable to show its own work.
CREATE TABLE alert (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       UUID NOT NULL REFERENCES tenant(id) ON DELETE CASCADE,
    ingest_run_id   BIGINT NOT NULL,
    work_item_id    BIGINT,
    ticket_id       BIGINT,
    -- Nullable and un-enumerated, for the same reason `reason` is: sprint_filter
    -- owns this vocabulary. It already emits values the first draft of this
    -- CHECK rejected ('P2-shaped', and NULL when both patterns abstain), which
    -- would have made the pilot record silently unable to store real output.
