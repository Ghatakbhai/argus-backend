-- 14. Phase 7.2 — GitHub App installation lifecycle. New at 7.2, D-133+.
--
-- The GitHub App itself (its id, private key, webhook secret) is ONE set of
-- credentials for the whole deployment, not per-tenant data, so it lives in
-- environment variables on the host (same discipline as ARGUS_ADMIN_SECRET),
-- never in this database. What Postgres tracks is which *installation* (a
-- GitHub org/user choosing to install that one App) belongs to which tenant.
--
-- `install_claim` is how that binding happens without ever trusting a caller
-- to name their own tenant: an admin action mints a one-time token FOR a
-- specific tenant; GitHub's install flow hands that token back on its setup
-- redirect; only then does an `integration` row get created (via the
-- SECURITY DEFINER `argus_claim_installation`, roles.sql). A webhook that
-- arrives for an installation nobody has claimed yet is recorded in
-- `pending_installation` (control-plane, not tenant data — there is no
-- tenant to scope it to yet) and otherwise ignored until it is.
-- ===========================================================================

CREATE TABLE install_claim (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id       UUID NOT NULL REFERENCES tenant(id) ON DELETE CASCADE,
    token_hash      TEXT NOT NULL UNIQUE,
    created_at      TEXT NOT NULL,
    expires_at      TEXT NOT NULL,
    redeemed_at     TEXT,
    UNIQUE (id, tenant_id)
);
CREATE INDEX ix_installclaim_tenant ON install_claim(tenant_id);

-- Control-plane, deliberately NOT tenant-scoped (excluded from the RLS loop
-- below, same as tenant_api_key/audit_log) — its whole purpose is to hold
-- installation events for accounts that have no tenant yet, so there is no
-- tenant_id to bind them to.
CREATE TABLE pending_installation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id     TEXT NOT NULL UNIQUE,
    account_login       TEXT NOT NULL,
    account_type        TEXT NOT NULL,
    status              TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending','claimed','suspended','deleted')),
    claimed_tenant_id   UUID REFERENCES tenant(id) ON DELETE SET NULL,
    first_seen_at       TEXT NOT NULL,
    last_seen_at        TEXT NOT NULL,
    last_event_type     TEXT,
    last_event_action   TEXT
);

-- Idempotency for GitHub's at-least-once delivery: `X-GitHub-Delivery` is a
-- UUID GitHub generates once per attempt-set and resends unchanged on retry.
-- Only meaningful once an installation is resolved to a tenant; the
-- unresolved case is deduplicated inside `pending_installation` itself
