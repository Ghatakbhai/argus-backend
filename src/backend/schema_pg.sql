-- ===========================================================================
-- ARGUS — Phase 7.1 multi-tenant Postgres schema
-- Ported from src/schema.sql (SQLite, Phase 2.1 + Phase 6.1/6.3) — D-124..D-128
--
-- Isolation model (D-125): ONE Postgres database, ONE schema, a `tenant_id`
-- column on every data table, and Postgres Row-Level Security FORCED on every
-- one of them. The API process connects as `argus_app`, a role with no
-- BYPASSRLS and no ownership of any table, and binds a tenant per request with
-- `SET LOCAL argus.tenant_id`. If that binding is missing the policies evaluate
-- to NULL and the query returns zero rows: it fails closed, never open.
--
-- Cross-tenant foreign keys are made physically impossible (D-126): every data
-- table carries UNIQUE (id, tenant_id) and every foreign key is composite,
-- carrying tenant_id through. A row in tenant A cannot reference a row in
-- tenant B even if the application tries.
--
-- Type fidelity (D-127): 0/1 integer flags and ISO-8601 TEXT timestamps are
-- kept exactly as Phase 2 defined them rather than "corrected" to BOOLEAN and
-- TIMESTAMPTZ, so the frozen engine's own SQL (detectors.py, sprint_filter.py,
-- digest.py — ~250KB of working, proven Phase 6 code) keeps running unchanged
-- against this database. CHECK constraints preserve the self-documentation.
-- ===========================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------------------------------------------------------------------------
-- 0. Control plane — tenants and their credentials.
--    These tables are deliberately NOT tenant-scoped: they are the thing that
--    resolves a request to a tenant in the first place. `argus_app` is granted
--    no direct read on tenant_api_key at all (see roles.sql); it can only call
--    the SECURITY DEFINER resolver below.
-- ---------------------------------------------------------------------------

CREATE TABLE tenant (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    slug            TEXT NOT NULL UNIQUE
                    CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$'),
    display_name    TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'shadow'
                    CHECK (status IN ('shadow','live','suspended','offboarded')),
    -- Phase 7.6's 2-week Shadow Mode is a tenant state, not a config flag
    -- buried in code: 'shadow' means detect and store but never DM a human.
    shadow_until    TEXT,
    created_at      TEXT NOT NULL,
    offboarded_at   TEXT
);

CREATE TABLE tenant_api_key (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id       UUID NOT NULL REFERENCES tenant(id) ON DELETE CASCADE,
    -- The plaintext key is shown exactly once, at creation, and never stored.
    key_prefix      TEXT NOT NULL UNIQUE,
    key_hash        TEXT NOT NULL,
    label           TEXT,
    created_at      TEXT NOT NULL,
    last_used_at    TEXT,
    revoked_at      TEXT
);
CREATE INDEX ix_apikey_tenant ON tenant_api_key(tenant_id);

-- Every tenant-bound request is recorded, including the ones that were
-- refused. Phase 9's SOC 2 conversation starts from this table existing.
CREATE TABLE audit_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       UUID REFERENCES tenant(id) ON DELETE SET NULL,
    at              TEXT NOT NULL,
    actor           TEXT NOT NULL,          -- 'tenant:<slug>' | 'admin' | 'anonymous'
    action          TEXT NOT NULL,
    detail          TEXT,
    outcome         TEXT NOT NULL CHECK (outcome IN ('ok','denied','error'))
);
CREATE INDEX ix_audit_tenant ON audit_log(tenant_id, at);

-- ---------------------------------------------------------------------------
-- The tenant binding. current_setting(..., true) returns NULL when unset,
-- so every RLS policy below evaluates to NULL -> no rows. Fail closed.
-- ---------------------------------------------------------------------------
CREATE FUNCTION argus_current_tenant() RETURNS uuid
    LANGUAGE sql STABLE
    AS $fn$ SELECT nullif(current_setting('argus.tenant_id', true), '')::uuid $fn$;

-- The only way `argus_app` can turn a presented key into a tenant.
-- SECURITY DEFINER so the app role never needs SELECT on tenant_api_key.
CREATE FUNCTION argus_resolve_api_key(p_prefix text, p_hash text)
    RETURNS TABLE (tenant_id uuid, key_id uuid, slug text, status text, shadow_until text)
    LANGUAGE sql SECURITY DEFINER STABLE
    AS $fn$
        SELECT t.id, k.id, t.slug, t.status, t.shadow_until
        FROM tenant_api_key k
        JOIN tenant t ON t.id = k.tenant_id
        WHERE k.key_prefix = p_prefix
          AND k.revoked_at IS NULL
          AND t.status <> 'offboarded'
          -- constant-time-ish compare; the token is 256 bits of entropy so a
          -- timing side channel here is not the realistic attack anyway
          AND k.key_hash = p_hash
    $fn$;

