    FOREIGN KEY (project_id, tenant_id)  REFERENCES project(id, tenant_id),
    FOREIGN KEY (author_id, tenant_id)   REFERENCES actor(id, tenant_id),
    FOREIGN KEY (fetch_id, tenant_id)    REFERENCES "fetch"(id, tenant_id)
);
CREATE INDEX ix_item_project ON work_item(tenant_id, snapshot_id, project_id, state);
CREATE INDEX ix_item_created ON work_item(tenant_id, snapshot_id, project_id, created_at);

-- 3. The event log ---------------------------------------------------------

CREATE TABLE event (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           UUID NOT NULL REFERENCES tenant(id) ON DELETE CASCADE,
    snapshot_id         BIGINT NOT NULL,
    work_item_id        BIGINT NOT NULL,
    type                TEXT NOT NULL CHECK (type IN (
                            'opened','closed','reopened','commented',
                            'review_submitted','review_requested','review_request_removed',
                            'assigned','unassigned','labeled','unlabeled',
                            'milestoned','demilestoned','committed','force_pushed',
                            'ready_for_review','converted_to_draft','renamed',
                            'referenced','cross_referenced','reacted','other')),
    actor_id            BIGINT,
    subject_actor_id    BIGINT,
    occurred_at         TEXT,
    date_precision      TEXT NOT NULL DEFAULT 'exact'
                        CHECK (date_precision IN ('exact','at_or_before','unknown')),
    counts_as_human     INTEGER NOT NULL DEFAULT 0 CHECK (counts_as_human IN (0,1)),
    human_reason        TEXT NOT NULL CHECK (human_reason IN (
                            'human','bot_account','ai_drafted_footnote',
                            'automation_event','unknown_actor')),
    detail              TEXT,
    fetch_id            BIGINT,
    UNIQUE (id, tenant_id),
    FOREIGN KEY (snapshot_id, tenant_id)      REFERENCES snapshot(id, tenant_id),
    FOREIGN KEY (work_item_id, tenant_id)     REFERENCES work_item(id, tenant_id),
    FOREIGN KEY (actor_id, tenant_id)         REFERENCES actor(id, tenant_id),
    FOREIGN KEY (subject_actor_id, tenant_id) REFERENCES actor(id, tenant_id),
    FOREIGN KEY (fetch_id, tenant_id)         REFERENCES "fetch"(id, tenant_id)
);
CREATE INDEX ix_event_item       ON event(tenant_id, work_item_id, occurred_at);
CREATE INDEX ix_event_item_human ON event(tenant_id, work_item_id, counts_as_human, occurred_at);
CREATE INDEX ix_event_actor      ON event(tenant_id, work_item_id, actor_id, counts_as_human, occurred_at);
CREATE INDEX ix_event_type       ON event(tenant_id, work_item_id, type, occurred_at);

